import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

// SVGs retain their standalone styles in source. Inline figures use the same
// rules in an external, figure-scoped sheet under the existing strict CSP.
const dir = path.resolve("content/notes/figures");
const output = ["/* Generated by scripts/prepare-note-figures.mjs. Do not edit by hand. */"];
for (const file of readdirSync(dir).filter(file => file.endsWith(".svg")).sort()) {
  const name = file.slice(0, -4);
  if (!/^[\w-]+$/.test(name)) throw new Error(`Invalid figure name: ${file}`);
  const svg = readFileSync(path.join(dir, file), "utf8");
  for (const match of svg.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)) {
    const css = match[1].replace(/\/\*[\s\S]*?\*\//g, "").trim();
    let end = 0;
    for (const rule of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
      if (css.slice(end, rule.index).trim()) throw new Error(`Unsupported SVG CSS in ${file}`);
      const selectors = rule[1].trim().split(",").map(selector => selector.trim());
      if (selectors.some(selector => !/^(?:[a-z][\w-]*|\.[\w-]+|#[\w-]+)$/.test(selector))) throw new Error(`Use simple SVG selectors in ${file}: ${rule[1]}`);
      output.push(`${selectors.map(selector => `.note-figure--${name} ${selector}`).join(", ")} { ${rule[2].trim()} }`);
      end = rule.index + rule[0].length;
    }
    if (css.slice(end).trim()) throw new Error(`Unsupported SVG CSS in ${file}`);
  }
}
writeFileSync(path.resolve("styles/note-figures.generated.css"), output.join("\n") + "\n");
console.log("Prepared external styles for note figures.");
